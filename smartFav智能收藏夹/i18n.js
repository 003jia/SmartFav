  function normalizeLanguage(language) {
    const value = String(language || '').replace('-', '_').toLowerCase();
    return value.startsWith('zh') ? 'zh_CN' : 'en';
  }

  function detectLanguage() {
    if (typeof chrome !== 'undefined' && chrome.i18n && chrome.i18n.getUILanguage) {
      return normalizeLanguage(chrome.i18n.getUILanguage());
    }
    if (typeof navigator !== 'undefined') return normalizeLanguage(navigator.language);
    return 'zh_CN';
  }

  function translate(language, key, variables = {}) {
    const locale = MESSAGES[normalizeLanguage(language)] || MESSAGES.zh_CN;
    const fallback = MESSAGES.zh_CN[key] || key;
    return String(locale[key] || fallback).replace(/\{\{(\w+)\}\}/g, (_, name) => {
      return Object.prototype.hasOwnProperty.call(variables, name) ? String(variables[name]) : '';
    });
  }

  function applyToDocument(language, root) {
    if (!root) return;
    const normalized = normalizeLanguage(language);
    if (root.documentElement) root.documentElement.lang = normalized === 'zh_CN' ? 'zh-CN' : 'en';
    const scope = root.querySelectorAll ? root : root.documentElement;
    scope.querySelectorAll('[data-i18n]').forEach((element) => {
      element.textContent = translate(normalized, element.dataset.i18n);
    });
    scope.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
      element.placeholder = translate(normalized, element.dataset.i18nPlaceholder);
    });
    scope.querySelectorAll('[data-i18n-aria-label]').forEach((element) => {
      element.setAttribute('aria-label', translate(normalized, element.dataset.i18nAriaLabel));
    });
    if (root.title !== undefined) root.title = translate(normalized, 'pageTitle');
  }

  const api = {
    SUPPORTED_LANGUAGES,
    MESSAGES,
    normalizeLanguage,
    detectLanguage,
    translate,
    applyToDocument
  };

  globalScope.SmartFavI18n = api;
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
